//! Experimental r2 common record/FIFO shared by runtime and host tests; no public ABI freeze.
//! Wire values match the r2 schema while retaining the existing experimental r1 values.
pub const SYS_TIME: u64 = 0x103;
pub const SYS_WAIT: u64 = 0x104;
pub const SYS_INPUT: u64 = 0x105;
pub const PERMISSION_TIME: u64 = 2;
pub const PERMISSION_WAIT: u64 = 4;
pub const PERMISSION_INPUT: u64 = 8;
pub const EVENT_BYTES: usize = 48;
pub const CAPACITY: usize = 64;
pub const KEY: u16 = 1;
pub const MOUSE: u16 = 2;
pub const GAMEPAD_BUTTON: u16 = 3;
pub const GAMEPAD_AXIS: u16 = 4;
pub const OVERFLOW: u16 = 5;
/// Copied values only. Wire encoding is explicit LE, never a borrowed user cast.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Event {
    pub kind: u16,
    pub flags: u32,
    pub timestamp_ms: u64,
    pub device: u32,
    pub code: u16,
    pub modifiers: u16,
    pub values: [i32; 3],
    pub buttons: u32,
}
impl Event {
    pub fn valid(&self) -> bool {
        match self.kind {
            KEY => {
                self.flags <= 1
                    && self.code <= 255
                    && self.modifiers <= 255
                    && self.values == [0; 3]
                    && self.buttons == 0
            }
            MOUSE => self.flags == 0 && self.code == 0 && self.modifiers == 0,
            GAMEPAD_BUTTON => {
                self.flags <= 1 && self.code < 32 && self.modifiers == 0 && self.values == [0; 3]
            }
            GAMEPAD_AXIS => {
                self.flags == 0
                    && self.code < 16
                    && self.modifiers == 0
                    && self.values[1..] == [0; 2]
                    && self.buttons == 0
            }
            _ => false, // Overflow records are generated by the queue, not producers.
        }
    }
    pub fn encode(self) -> [u8; EVENT_BYTES] {
        let mut out = [0; EVENT_BYTES];
        out[..2].copy_from_slice(&(EVENT_BYTES as u16).to_le_bytes());
        out[2..4].copy_from_slice(&self.kind.to_le_bytes());
        out[4..8].copy_from_slice(&self.flags.to_le_bytes());
        out[8..16].copy_from_slice(&self.timestamp_ms.to_le_bytes());
        out[16..20].copy_from_slice(&self.device.to_le_bytes());
        out[20..22].copy_from_slice(&self.code.to_le_bytes());
        out[22..24].copy_from_slice(&self.modifiers.to_le_bytes());
        for (n, value) in self.values.iter().enumerate() {
            out[24 + n * 4..28 + n * 4].copy_from_slice(&value.to_le_bytes());
        }
        out[36..40].copy_from_slice(&self.buttons.to_le_bytes());
        out // bytes40..48 reserved zero; no stack padding is exposed.
    }
}
pub struct Queue {
    entries: [Event; CAPACITY],
    head: usize,
    count: usize,
    lost: u32,
}
impl Default for Queue {
    fn default() -> Self {
        Self {
            entries: [Event::default(); CAPACITY],
            head: 0,
            count: 0,
            lost: 0,
        }
    }
}
impl Queue {
    pub fn push(&mut self, event: Event) -> bool {
        if !event.valid() {
            return false;
        }
        if self.count == CAPACITY || self.lost != 0 {
            self.lost = self.lost.saturating_add(1);
            return false;
        }
        self.entries[(self.head + self.count) % CAPACITY] = event;
        self.count += 1;
        true
    }
    pub fn pending(&self) -> bool {
        self.count != 0 || self.lost != 0
    }
    pub fn pop(&mut self, now_ms: u64) -> Option<Event> {
        if self.count != 0 {
            let event = self.entries[self.head];
            self.head = (self.head + 1) % CAPACITY;
            self.count -= 1;
            Some(event)
        } else if self.lost != 0 {
            let lost = core::mem::take(&mut self.lost);
            Some(Event {
                kind: OVERFLOW,
                timestamp_ms: now_ms,
                buttons: lost,
                ..Event::default()
            })
        } else {
            None
        }
    }
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum WaitState {
    Input,
    Timeout,
    Poll,
}
/// Zero timeout is a nonblocking yield/poll; input wins over an elapsed deadline.
/// Actual USB progress, checked copyout and clock wiring live in boot/src/ring3/io.rs.
pub fn wait_state(now_ms: u64, deadline_ms: u64, input_pending: bool) -> WaitState {
    if input_pending {
        WaitState::Input
    } else if now_ms >= deadline_ms {
        WaitState::Timeout
    } else {
        WaitState::Poll
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn wire_and_relative_mouse_not_absolute_tablet() {
        let mouse = Event {
            kind: MOUSE,
            timestamp_ms: 0x0102030405060708,
            values: [-1, 17, -2],
            buttons: 5,
            ..Event::default()
        };
        assert!(mouse.valid());
        let out = mouse.encode();
        assert_eq!(&out[..4], &[48, 0, 2, 0]);
        assert_eq!(&out[8..16], &mouse.timestamp_ms.to_le_bytes());
        assert_eq!(&out[24..28], &(-1i32).to_le_bytes());
        assert_eq!(&out[40..], &[0; 8]);
        assert!(!Event { flags: 2, ..mouse }.valid()); // no absolute flag accepted
    }
    #[test]
    fn keyboard_and_gamepad_bounds() {
        let key = Event {
            kind: KEY,
            flags: 1,
            code: 0xe1,
            modifiers: 2,
            ..Event::default()
        };
        assert!(key.valid());
        assert!(!Event { code: 256, ..key }.valid());
        assert!(
            !Event {
                modifiers: 256,
                ..key
            }
            .valid()
        );
        assert!(
            Event {
                kind: GAMEPAD_BUTTON,
                flags: 0,
                code: 31,
                ..Event::default()
            }
            .valid()
        );
        assert!(
            !Event {
                kind: GAMEPAD_BUTTON,
                code: 32,
                ..Event::default()
            }
            .valid()
        );
        assert!(
            Event {
                kind: GAMEPAD_AXIS,
                code: 15,
                values: [i32::MIN, 0, 0],
                ..Event::default()
            }
            .valid()
        );
        assert!(
            !Event {
                kind: GAMEPAD_AXIS,
                code: 16,
                ..Event::default()
            }
            .valid()
        );
    }
    #[test]
    fn overflow_fifo_order_and_reuse() {
        let mut q = Queue::default();
        assert_eq!(q.pop(0), None);
        for n in 0..CAPACITY {
            assert!(q.push(Event {
                kind: KEY,
                code: n as u16,
                ..Event::default()
            }));
        }
        assert!(!q.push(Event {
            kind: MOUSE,
            ..Event::default()
        }));
        assert_eq!(q.pop(1).unwrap().code, 0);
        assert!(!q.push(Event {
            kind: MOUSE,
            ..Event::default()
        }));
        for n in 1..CAPACITY {
            assert_eq!(q.pop(1).unwrap().code, n as u16);
        }
        let overflow = q.pop(9).unwrap();
        assert_eq!(
            (overflow.kind, overflow.buttons, overflow.timestamp_ms),
            (OVERFLOW, 2, 9)
        );
        assert!(!q.pending());
        for _ in 0..128 {
            assert!(q.push(Event {
                kind: MOUSE,
                ..Event::default()
            }));
            assert!(q.pop(10).is_some());
        }
    }
    #[test]
    fn wait_zero_timeout_input_priority_and_large_time() {
        assert_eq!(wait_state(0, 0, false), WaitState::Timeout);
        assert_eq!(wait_state(7, 8, false), WaitState::Poll);
        assert_eq!(wait_state(8, 8, false), WaitState::Timeout);
        assert_eq!(wait_state(u64::MAX, u64::MAX, true), WaitState::Input);
        assert_eq!(wait_state(u64::MAX, u64::MAX, false), WaitState::Timeout);
    }
}
